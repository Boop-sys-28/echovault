function getDeterministicExpandedUserCount(id: string, index: number): number {
  if (EXPANDED_BASELINE_USER_COUNTS[id]) {
    return EXPANDED_BASELINE_USER_COUNTS[id];
  }
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash * 31 + id.charCodeAt(i)) % 2750;
  }
  return 450 + ((hash + index * 137) % 2750);
}

